app.post('/spaces/:spaceId/documents', async (req, res) => {
  const relayStarted = Date.now();
  const userId = req.get(USER_HEADER)?.trim();
  const requestId = String(res.locals.requestId);
  if (!userId) return res.status(401).json({ error: 'X-User-Id is required', status: 401, requestId });
  const contentType = req.get('content-type') ?? '';
  if (!contentType.toLowerCase().startsWith('multipart/form-data')) {
    return res.status(400).json({ error: 'multipart/form-data is required', status: 400, requestId });
  }
  try {
    const upstream = await fetch(`${env.agentUrl}/spaces/${encodeURIComponent(req.params.spaceId)}/documents`, {
      method: 'POST',
      headers: {
        'content-type': contentType, [USER_HEADER]: userId, [REQUEST_HEADER]: requestId,
        // The multipart stream is forwarded unchanged. Preserve its known size
        // so the private hop need not use chunked transfer framing.
        ...(req.get('content-length')?.match(/^\d+$/)
          ? { 'content-length': req.get('content-length')! } : {})
      },
      body: req,
      duplex: 'half',
      signal: AbortSignal.timeout(30000)
    });
    const responseHeadersAt = Date.now();
    const body: unknown = await upstream.json();
    log.info({ requestId, userId, spaceId: req.params.spaceId, upstreamStatus: upstream.status,
      ingressWaitMs: res.locals.ingressWaitMs,
      forwardedContentLength: req.get('content-length') ?? null,
      upstreamResponseMs: responseHeadersAt - relayStarted,
      responseParseMs: Date.now() - responseHeadersAt, relayMs: Date.now() - relayStarted
    }, 'document upload relay completed');
    if (!upstream.ok) return res.status(upstream.status).json(body);
    return res.status(202).json(UploadDocumentResponse.parse(body));
  } catch (error) {
    log.error({ requestId, userId, spaceId: req.params.spaceId, relayMs: Date.now() - relayStarted, errorName: error instanceof Error ? error.name : 'unknown' }, 'agent upload request failed');
    return res.status(502).json({ error: 'agent service failed while uploading document', status: 502, requestId });
  }
});

// ---------------------------------------------------------------- Quick ask (SSE pass-through)

app.post('/threads/:threadId/ask', async (req, res) => {
  const proxyStarted = Date.now();
  const userId = req.get(USER_HEADER)?.trim();
  const requestId = String(res.locals.requestId);
  if (!userId) {
    return res.status(401).json({ error: 'X-User-Id is required', status: 401, requestId });
  }
  const parsedBody = AskBody.safeParse(req.body ?? {});
  if (!parsedBody.success) {
    return res.status(400).json({ error: 'invalid request body', status: 400, requestId });
  }
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(new Error('Agent answer timed out')),
    parsedBody.data.depth === 'deep' ? 255000 : 105000);
  // A silent upstream must not occupy the browser for several minutes.
  // Keep a separate first-response deadline; the wider timer covers active SSE.
  const headerTimeout = setTimeout(() => controller.abort(new Error('Agent did not start a response within 30 seconds')), 30000);
  const onClose = () => {
    if (!res.writableFinished) controller.abort(new Error('Client disconnected during answer'));
  };
  res.once('close', onClose);
  log.info({ requestId, userId, threadId: req.params.threadId, depth: parsedBody.data.depth }, 'agent ask request started');
  try {
    const upstream = await fetch(`${env.agentUrl}/threads/${encodeURIComponent(req.params.threadId)}/ask`, {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        [USER_HEADER]: userId,
        [REQUEST_HEADER]: requestId
      },
      body: JSON.stringify(parsedBody.data),
      signal: controller.signal
    });
    clearTimeout(headerTimeout);
    log.info({ requestId, upstreamHeadersMs: Date.now() - proxyStarted, depth: parsedBody.data.depth }, 'ask upstream headers timing');
    const contentType = upstream.headers.get('content-type') ?? '';
    if (!upstream.ok || !contentType.includes('text/event-stream')) {
      const text = await upstream.text();
      res.status(upstream.status).type(contentType || 'application/json');
      return res.send(text);
    }

    res.status(upstream.status);
    res.setHeader('Content-Type', 'text/event-stream; charset=utf-8');
    res.setHeader('Cache-Control', 'no-cache, no-transform');
    res.setHeader('Connection', 'keep-alive');
    res.setHeader('X-Accel-Buffering', 'no');
    res.flushHeaders();
    const reader = upstream.body?.getReader();
    if (!reader) return res.end();
    let firstFrame = true;
    try {
      while (true) {
        const { done, value } = await reader.read();
        if (done) break;
        if (firstFrame) {
          firstFrame = false;
          log.info({ requestId, firstFrameMs: Date.now() - proxyStarted, depth: parsedBody.data.depth }, 'ask first frame timing');
        }
        if (!res.write(Buffer.from(value))) await once(res, 'drain', { signal: controller.signal });
      }
      return res.end();
    } finally {
      try { await reader.cancel(); } catch { /* An aborted upstream is already closed. */ }
      reader.releaseLock();
    }
  } catch (error) {
    log.error({ error: error instanceof Error ? error.message : 'unknown upstream failure', requestId, userId, threadId: req.params.threadId, errorName: error instanceof Error ? error.name : 'unknown' }, 'agent ask request failed');
    if (res.destroyed) return;
    if (res.headersSent) {
      res.write(`event: error\ndata: ${JSON.stringify({ error: 'agent service failed while answering', status: 502, requestId })}\n\n`);
      return res.end();
    }
    return res.status(502).json({ error: controller.signal.aborted
      ? String(controller.signal.reason instanceof Error ? controller.signal.reason.message : 'agent request aborted')
      : 'agent service failed while answering', status: 502, requestId });
  } finally {
    clearTimeout(headerTimeout);
    clearTimeout(timeout);
    res.off('close', onClose);
  }
});

// ---------------------------------------------------------------- everything else: 501

/**
 * Every contract route answers 501 until you implement it. The UI renders that as
 * "not implemented yet", so the interface is your progress bar: each route you finish
 * lights up a piece of the product.
 */
const notImplemented = (route: string) => (_req: express.Request, res: express.Response) => {
  res.status(501).json({
    error: `not implemented yet: ${route}. Build it in backend/gateway/src/.`,
    status: 501,
    requestId: String(res.locals.requestId)
  });
};

for (const declaredRoute of ROUTES) {
  // Widen the generated route union so this defensive fallback remains valid
  // when the contract gains a route in a future revision.
  const route: { method: string; path: string } = declaredRoute;
  if (
    route.path === '/health' ||
    route.path === '/evals/report.json' ||
    route.path === '/stats' ||
    (route.method === 'POST' && route.path === '/threads') ||
    (route.method === 'GET' && route.path === '/threads') ||
    (route.method === 'GET' && route.path === '/threads/:threadId') ||
    (route.method === 'POST' && route.path === '/threads/:threadId/ask') ||
    (route.method === 'GET' && route.path === '/memory') ||
    (route.method === 'DELETE' && route.path === '/memory/:memoryId') ||
    (route.method === 'POST' && route.path === '/spaces') ||
    (route.method === 'GET' && route.path === '/spaces') ||
    (route.method === 'POST' && route.path === '/spaces/:spaceId/documents') ||
    (route.method === 'GET' && route.path === '/spaces/:spaceId/documents')
  ) continue;
  const path = route.path.replace(/:(\w+)/g, ':$1');
  const method = route.method.toLowerCase() as 'get' | 'post' | 'delete';
  app[method](path, notImplemented(`${route.method} ${route.path}`));
}

